# Saves package lists, device props and every setting we will touch, plus an undo script.
. "$PSScriptRoot\common.ps1"
$stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
$dir = Join-Path $Root "backup\$stamp"
New-Item -ItemType Directory -Force $dir | Out-Null

New-Item -ItemType File "$dir\packages-disabled.txt" -Force | Out-Null  # stays empty when nothing is disabled
Adb-Raw shell pm list packages -f   | Set-Content "$dir\packages-all.txt"
Adb-Raw shell pm list packages -d   | Set-Content "$dir\packages-disabled.txt"
Adb-Raw shell pm list packages -3   | Set-Content "$dir\packages-thirdparty.txt"
Adb-Raw shell pm list packages -s   | Set-Content "$dir\packages-system.txt"
Adb-Raw shell getprop               | Set-Content "$dir\getprop.txt"

$keys = 'window_animation_scale','transition_animation_scale','animator_duration_scale','private_dns_mode','private_dns_specifier'
$settings = [ordered]@{}
foreach ($k in $keys) { $settings[$k] = (Adb-Raw shell settings get global $k | Out-String).Trim() }
$settings | ConvertTo-Json | Set-Content "$dir\settings.json"

# Undo for settings (packages are appended by apply.ps1 as they are disabled).
$undo = @('# Generated by backup.ps1 - restores the TV to the state saved in this folder', '. "$PSScriptRoot\..\..\common.ps1"')
foreach ($k in $keys) {
    $v = $settings[$k]
    $undo += if ($v -eq 'null' -or -not $v) { "Invoke-Adb shell settings delete global $k" } else { "Invoke-Adb shell settings put global $k $v" }
}
$undo | Set-Content "$dir\undo.ps1"
Set-Content (Join-Path $Root 'backup\LATEST') $dir
Write-Log "Backup saved to $dir" 'Green'
$settings
